#pragma once

// Project = everything the studio knows about one level: palette, layers,
// masks, channel allocations, generation settings and the registry of the
// objects it generated.
//
// Persistence strategy (see docs/PERSISTENCE.md):
//   * The level itself only contains native GD objects. Nothing the studio
//     stores is needed to DISPLAY the level, so it works without the mod.
//   * Each generated object carries ONE extra group: the tag group of its
//     studio layer (a high group id that no trigger of the level references).
//     This survives copy/paste, level copies, uploads and manual edits.
//   * The project file (JSON, in the mod's save folder) keeps the full record
//     of every generated object: layer, operation, placement key and the
//     fingerprint of its exact object string.
//   * When the editor opens, records are reconciled with the live objects:
//     exact fingerprint match -> linked; tagged object without exact match ->
//     modified by the user; record without object -> deleted by the user;
//     tagged object without record -> recovered into its layer.

