// Generation tab: engines, global parameters, preview / apply and history.

#include "StudioPopup.hpp"
#include "Toolbar.hpp"

using namespace geode::prelude;

namespace {

void runAll(StudioPopup* popup, gdds::OperationMode mode) {
    auto s = popup->session();
    s->commitConfigEdit("generation settings");
    gdds::GenerationRequest req;
    req.mode = mode;
    s->run(req);
    popup->setStatus(s->lastStatus());
    Toolbar::refreshCurrent();
}

}  // namespace

void tabs::buildGenerate(StudioPopup* popup, ui::Column& col) {
    auto s = popup->session();
    auto& settings = s->project().settings;

    col.title("Engines");
    col.toggleRow("Structural (block design, outlines, corners, textures, details)", settings.structural,
                  [s](bool on) { s->beginConfigEdit(); s->project().settings.structural = on; });
    col.toggleRow("Lighting (structural glow, ambient glow, highlights)", settings.lighting,
                  [s](bool on) { s->beginConfigEdit(); s->project().settings.lighting = on; });
    col.toggleRow("Artistic (background, atmosphere, foreground)", settings.artistic,
                  [s](bool on) { s->beginConfigEdit(); s->project().settings.artistic = on; });

    col.title("Global");
    col.slider("Global density", float(settings.globalDensity), 0.1f, 2.f, [s](float v) {
        s->beginConfigEdit();
        s->project().settings.globalDensity = v;
    });
    col.input("Global seed", std::to_string(settings.globalSeed), [s](std::string v) {
        if (v.empty()) return;
        s->beginConfigEdit();
        s->project().settings.globalSeed = std::strtoull(v.c_str(), nullptr, 10);
    }, "0123456789");
    {
        auto menu = col.row(26);
        auto l = ui::label("Hand-modified objects", 0.32f);
        l->setAnchorPoint({0, 0.5f});
        l->setPosition({4, 0});
        menu->addChild(l);
        auto policy = settings.modifiedPolicy;
        auto btn = ui::button(gdds::modifiedPolicyName(policy), [popup, s, policy] {
            s->beginConfigEdit();
            s->project().settings.modifiedPolicy = gdds::ModifiedPolicy((int(policy) + 1) % 3);
            popup->refresh();
        }, 0.45f);
        btn->setPosition({col.width() * 0.65f, 0});
        menu->addChild(btn);
    }
    col.toggleRow("Tag generated objects with one group per layer (recommended)", settings.useTagGroups,
                  [s](bool on) { s->beginConfigEdit(); s->project().settings.useTagGroups = on; });

    col.title("Generate the whole level");
    if (s->studio().hasPendingPreview()) {
        col.text("A preview is shown in the editor (cyan outlines).", 0.32f, ui::kAccent);
        col.buttons({{"Apply preview", [popup, s] {
                          auto out = s->studio().applyPreview();
                          s->report(out);
                          s->save();
                          Toolbar::refreshCurrent();
                          popup->refresh();
                      }},
                     {"Cancel preview", [popup, s] {
                          s->studio().cancelPreview();
                          Toolbar::refreshCurrent();
                          popup->refresh();
                      }}});
    }
    col.buttons({{"Preview", [popup, s] {
                      s->commitConfigEdit("generation settings");
                      gdds::GenerationRequest req;
                      req.mode = gdds::OperationMode::Regenerate;
                      if (s->preview(req)) popup->hideForEditing();
                      Toolbar::refreshCurrent();
                  }},
                 {"Generate", [popup] { runAll(popup, gdds::OperationMode::Generate); }},
                 {"Regenerate", [popup] { runAll(popup, gdds::OperationMode::Regenerate); }}},
                0.45f);
    col.buttons({{"Remove all decoration", [popup, s] {
                     geode::createQuickPopup("Remove decoration",
                                             "Remove <cy>every object generated by the studio</c> (unlocked layers)?\nGameplay "
                                             "and your own decoration are not affected.",
                                             "Cancel", "Remove", [popup](auto, bool yes) {
                                                 if (yes && StudioPopup::current()) runAll(popup, gdds::OperationMode::Remove);
                                             });
                 }}},
                0.42f);

    col.title("History");
    auto& h = s->studio().history();
    col.text(fmt::format("Undo: {}   Redo: {}", h.peekUndo() ? h.peekUndo()->description : "-",
                         h.peekRedo() ? h.peekRedo()->description : "-"),
             0.3f);
    col.buttons({{"Undo", [popup, s] {
                      if (s->studio().undo()) s->status("Undone"); else s->status("Nothing to undo");
                      s->save();
                      popup->refresh();
                  }},
                 {"Redo", [popup, s] {
                      if (s->studio().redo()) s->status("Redone"); else s->status("Nothing to redo");
                      s->save();
                      popup->refresh();
                  }},
                 {"Restore config", [popup, s] {
                      if (s->studio().restorePreviousConfiguration()) s->status("Previous configuration restored");
                      else s->status("No previous configuration");
                      s->save();
                      popup->refresh();
                  }}},
                0.42f);
    col.text("The studio keeps its own history: GD's undo button does not undo studio operations "
             "(but deleting generated objects by hand is detected).",
             0.28f);

    col.title("Readability & safety");
    for (auto& line : {std::string("Gameplay objects are compared before/after every operation; any difference rolls it back."),
                       std::string("Only verified decoration objects are generated."),
                       std::string("Readability uses conservative rules (hazard margins, corridor tightness, draw order). "
                                   "Player trajectories are NOT simulated.")})
        col.text("- " + line, 0.28f);
}
