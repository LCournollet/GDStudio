// Layers tab: the layer tree and the selected layer's own parameters.

#include "Prompt.hpp"
#include "StudioPopup.hpp"
#include "Toolbar.hpp"

#include <gdds/Layer.hpp>

using namespace geode::prelude;

namespace {

bool g_addingLayer = false;
bool g_addingChild = false;

char const* const kZNames[] = {"B5", "B4", "B3", "B2", "B1", "T1", "T2", "T3", "T4"};

void layerOp(StudioPopup* popup, gdds::OperationMode mode, bool preview) {
    auto s = popup->session();
    s->commitConfigEdit("layer settings");
    gdds::GenerationRequest req;
    req.mode = mode;
    req.layers = {s->selectedLayer};
    if (preview) {
        if (s->preview(req)) popup->hideForEditing();
        Toolbar::refreshCurrent();
        return;
    }
    s->run(req);
    popup->setStatus(s->lastStatus());
    Toolbar::refreshCurrent();
}

void addLayerOfKind(StudioPopup* popup, gdds::LayerKind kind, bool asChild) {
    auto s = popup->session();
    s->beginConfigEdit();
    gdds::Layer l;
    l.kind = kind;
    l.name = gdds::layerKindLabel(kind);
    auto styles = gdds::stylesFor(kind);
    l.params.style = styles.front() == "default" ? "" : styles.front();
    l.params.seed = uint64_t(std::rand() % 100000);
    auto sel = s->project().layers.find(s->selectedLayer);
    if (asChild && sel) l.parentId = sel->kind == gdds::LayerKind::Group ? sel->id : sel->parentId;
    else if (sel) l.parentId = sel->parentId;
    // Reuse the objects of a layer of the same kind as a starting point.
    for (auto& other : s->project().layers.all())
        if (other.kind == kind && !other.objects.empty()) { l.objects = other.objects; break; }
    auto& added = s->project().layers.add(l, sel ? sel->id : "");
    s->selectedLayer = added.id;
    s->commitConfigEdit("add layer");
    g_addingLayer = false;
    popup->refresh();
}

}  // namespace

void tabs::buildLayers(StudioPopup* popup, ui::Column& col) {
    auto s = popup->session();
    auto& project = s->project();
    auto& stack = project.layers;
    auto counts = project.objectCountByLayer();

    // The object selected in the editor: show its layer.
    auto selected = s->backend().selectedObjects();
    if (!selected.empty()) {
        auto lid = s->studio().layerOfObject(selected.front());
        if (auto l = stack.find(lid))
            col.text("Selected object belongs to layer: " + l->name + (selected.size() > 1 ? fmt::format(" (+{} more objects)", selected.size() - 1) : ""),
                     0.32f, ui::kAccent);
        else col.text("Selected object is not generated by the studio.", 0.3f);
    }

    col.title("Layers");
    {
        auto head = col.row(14);
        auto addHead = [&](char const* t, float x) {
            auto l = ui::label(t, 0.24f, ui::kMuted);
            l->setPosition({x, 0});
            head->addChild(l);
        };
        addHead("show", 14);
        addHead("lock", 38);
        addHead("on", 62);
        addHead("objects", col.width() - 24);
    }
    for (auto& id : stack.displayOrder()) {
        auto layer = stack.find(id);
        if (!layer) continue;
        bool isSel = id == s->selectedLayer;
        auto menu = col.row(22, isSel ? ui::kRowSelected : ui::kRow);
        int depth = stack.depthOf(id);
        auto vis = ui::toggle(layer->visible, [s, id](bool on) {
            if (auto l = s->project().layers.find(id)) l->visible = on;
            s->studio().refreshVisibility();
            s->save();
        }, 0.38f);
        vis->setPosition({14, 0});
        menu->addChild(vis);
        auto lock = ui::toggle(layer->locked, [s, id](bool on) {
            if (auto l = s->project().layers.find(id)) l->locked = on;
            s->save();
        }, 0.38f);
        lock->setPosition({38, 0});
        menu->addChild(lock);
        auto en = ui::toggle(layer->enabled, [s, id](bool on) {
            if (auto l = s->project().layers.find(id)) l->enabled = on;
            s->save();
        }, 0.38f);
        en->setPosition({62, 0});
        menu->addChild(en);

        std::string name = std::string(size_t(depth) * 2, ' ') + (layer->kind == gdds::LayerKind::Group ? "[+] " : "") + layer->name;
        auto nameLabel = ui::label(name, 0.33f, isSel ? ui::kAccent : ui::kText);
        ui::fitLabel(nameLabel, col.width() - 150);
        auto nameBtn = CCMenuItemExt::createSpriteExtra(nameLabel, [popup, s, id](auto) {
            s->selectedLayer = id;
            popup->refresh();
        });
        nameBtn->setAnchorPoint({0, 0.5f});
        nameBtn->setPosition({80.f + depth * 8.f, 0});
        menu->addChild(nameBtn);
        int count = 0;
        for (auto& sub : stack.subtree(id)) count += counts[sub];
        auto cl = ui::label(std::to_string(count), 0.3f, ui::kMuted);
        cl->setAnchorPoint({1, 0.5f});
        cl->setPosition({col.width() - 6, 0});
        menu->addChild(cl);
    }

    col.buttons({
        {"+ Layer", [popup] { g_addingLayer = !g_addingLayer; g_addingChild = false; popup->refresh(); }},
        {"+ Sub", [popup] { g_addingLayer = !g_addingLayer; g_addingChild = true; popup->refresh(); }},
        {"Duplicate", [popup, s] {
             if (s->selectedLayer.empty()) return;
             s->beginConfigEdit();
             s->selectedLayer = s->project().layers.duplicate(s->selectedLayer);
             s->commitConfigEdit("duplicate layer");
             popup->refresh();
         }},
        {"Delete", [popup, s] {
             auto id = s->selectedLayer;
             auto l = s->project().layers.find(id);
             if (!l) return;
             geode::createQuickPopup("Delete layer",
                                     fmt::format("Delete <cy>{}</c> and remove all of its generated objects from the level?", l->name),
                                     "Cancel", "Delete", [popup, s, id](auto, bool yes) {
                                         if (!yes) return;
                                         auto out = s->studio().deleteLayer(id);
                                         s->report(out);
                                         s->save();
                                         s->selectedLayer.clear();
                                         if (StudioPopup::current()) popup->refresh();
                                     });
         }},
    });
    col.buttons({
        {"Up", [popup, s] { s->beginConfigEdit(); s->project().layers.move(s->selectedLayer, -1); s->commitConfigEdit("reorder"); popup->refresh(); }},
        {"Down", [popup, s] { s->beginConfigEdit(); s->project().layers.move(s->selectedLayer, 1); s->commitConfigEdit("reorder"); popup->refresh(); }},
        {"Rename", [popup, s] {
             auto l = s->project().layers.find(s->selectedLayer);
             if (!l) return;
             auto id = l->id;
             TextPrompt::create("Rename layer", l->name, [popup, s, id](std::string name) {
                 s->beginConfigEdit();
                 s->project().layers.rename(id, name);
                 s->commitConfigEdit("rename layer");
                 if (StudioPopup::current()) popup->refresh();
             })->show();
         }},
        {"+ Group", [popup, s] {
             s->beginConfigEdit();
             gdds::Layer g;
             g.kind = gdds::LayerKind::Group;
             g.name = "Group";
             s->selectedLayer = s->project().layers.add(g).id;
             s->commitConfigEdit("add group");
             popup->refresh();
         }},
    });

    if (g_addingLayer) {
        col.text(g_addingChild ? "Choose the kind of the new sub-layer:" : "Choose the kind of the new layer:", 0.3f, ui::kAccent);
        std::vector<std::pair<std::string, std::function<void()>>> row;
        for (int k = 1; k < gdds::kLayerKindCount; ++k) {
            auto kind = gdds::LayerKind(k);
            row.push_back({gdds::layerKindLabel(kind), [popup, kind] { addLayerOfKind(popup, kind, g_addingChild); }});
            if (row.size() == 3) {
                col.buttons(row, 0.32f);
                row.clear();
            }
        }
        if (!row.empty()) col.buttons(row, 0.32f);
    }

    // ---- selected layer -----------------------------------------------------------
    auto layer = stack.find(s->selectedLayer);
    if (!layer) {
        col.text("Select a layer to edit its parameters.");
        return;
    }
    auto id = layer->id;
    col.title("Layer: " + layer->name);
    col.text(fmt::format("Kind: {}  -  {} objects  -  tag group {}{}", gdds::layerKindLabel(layer->kind), counts[id],
                         layer->tagGroup, stack.isLocked(id) ? "  -  LOCKED" : ""),
             0.3f);
    if (layer->kind == gdds::LayerKind::Group) {
        col.buttons({{"Generate group", [popup] { layerOp(popup, gdds::OperationMode::Generate, false); }},
                     {"Remove objects", [popup] { layerOp(popup, gdds::OperationMode::Remove, false); }}});
        return;
    }
    auto edit = [s, id](auto fn) {
        s->beginConfigEdit();
        if (auto l = s->project().layers.find(id)) fn(*l);
    };

    // Style
    auto styles = gdds::stylesFor(layer->kind);
    if (styles.size() > 1) {
        auto menu = col.row(26);
        auto l = ui::label("Style", 0.32f);
        l->setAnchorPoint({0, 0.5f});
        l->setPosition({4, 0});
        menu->addChild(l);
        std::string current = layer->params.style.empty() ? styles.front() : layer->params.style;
        auto btn = ui::button(current, [popup, s, id, styles, current] {
            auto it = std::find(styles.begin(), styles.end(), current);
            size_t next = it == styles.end() ? 0 : (size_t(it - styles.begin()) + 1) % styles.size();
            s->beginConfigEdit();
            if (auto l = s->project().layers.find(id)) l->params.style = styles[next];
            popup->refresh();
        }, 0.45f);
        btn->setPosition({col.width() * 0.6f, 0});
        menu->addChild(btn);
    }
    col.slider("Density", float(layer->params.density), 0, 1, [edit](float v) { edit([v](gdds::Layer& l) { l.params.density = v; }); });
    col.slider("Complexity", float(layer->params.complexity), 0, 1, [edit](float v) { edit([v](gdds::Layer& l) { l.params.complexity = v; }); });
    col.slider("Scale", float(layer->params.scale), 0.3f, 2.5f, [edit](float v) { edit([v](gdds::Layer& l) { l.params.scale = v; }); });
    // Intensity and opacity only change color channels: applied live.
    col.slider("Intensity", float(layer->params.intensity), 0, 2, [edit, s](float v) {
        edit([v](gdds::Layer& l) { l.params.intensity = v; });
        s->studio().applyColors();
    });
    col.slider("Opacity", float(layer->params.opacity), 0, 1, [edit, s](float v) {
        edit([v](gdds::Layer& l) { l.params.opacity = v; });
        s->studio().applyColors();
    });
    col.input("Seed", std::to_string(layer->params.seed), [edit](std::string v) {
        if (v.empty()) return;
        edit([v](gdds::Layer& l) { l.params.seed = std::strtoull(v.c_str(), nullptr, 10); });
    }, "0123456789");
    col.toggleRow("Automatic Z layer (relative to the gameplay)", layer->params.autoZ, [popup, edit](bool on) {
        edit([on](gdds::Layer& l) { l.params.autoZ = on; });
        popup->refresh();
    });
    if (!layer->params.autoZ) {
        auto menu = col.row(26);
        auto l = ui::label("Z layer / Z order", 0.32f);
        l->setAnchorPoint({0, 0.5f});
        l->setPosition({4, 0});
        menu->addChild(l);
        int zl = layer->params.zLayer == 0 ? gdds::zlayer::B2 : layer->params.zLayer;
        auto zbtn = ui::button(gdds::zlayer::name(zl), [popup, s, id, zl] {
            int idx = std::max(0, gdds::zlayer::rank(zl));
            auto next = gdds::zlayer::fromName(kZNames[(idx + 1) % 9]);
            s->beginConfigEdit();
            if (auto l = s->project().layers.find(id)) l->params.zLayer = next;
            popup->refresh();
        }, 0.45f);
        zbtn->setPosition({col.width() * 0.55f, 0});
        menu->addChild(zbtn);
        col.input("Z order", std::to_string(layer->params.zOrder), [edit](std::string v) {
            if (v.empty() || v == "-") return;
            edit([v](gdds::Layer& l) { l.params.zOrder = std::atoi(v.c_str()); });
        }, "-0123456789");
    }
    {
        auto menu = col.row(26);
        auto l = ui::label("Mask border policy", 0.32f);
        l->setAnchorPoint({0, 0.5f});
        l->setPosition({4, 0});
        menu->addChild(l);
        auto policy = layer->params.boundary;
        auto btn = ui::button(gdds::boundaryPolicyName(policy), [popup, s, id, policy] {
            s->beginConfigEdit();
            if (auto l = s->project().layers.find(id)) l->params.boundary = gdds::BoundaryPolicy((int(policy) + 1) % 3);
            popup->refresh();
        }, 0.45f);
        btn->setPosition({col.width() * 0.6f, 0});
        menu->addChild(btn);
    }
    col.buttons({{"Colors of this layer", [popup, s] {
                      s->editLayerPalette = true;
                      popup->showTab(StudioPopup::Colors);
                  }},
                 {"Objects of this layer", [popup] { popup->showTab(StudioPopup::Objects); }}},
                0.4f);
    col.title("Operations on this layer");
    col.buttons({{"Preview", [popup] { layerOp(popup, gdds::OperationMode::Regenerate, true); }},
                 {"Generate", [popup] { layerOp(popup, gdds::OperationMode::Generate, false); }},
                 {"Regenerate", [popup] { layerOp(popup, gdds::OperationMode::Regenerate, false); }},
                 {"Remove", [popup] { layerOp(popup, gdds::OperationMode::Remove, false); }}},
                0.42f);
    col.buttons({{"Select its objects", [popup, s, id] {
                      auto l = s->project().layers.find(id);
                      int n = l ? s->backend().selectObjectsWithGroups({l->tagGroup}) : 0;
                      popup->setStatus(fmt::format("{} objects selected in the editor", n));
                  }},
                 {"Move selection here", [popup, s, id] {
                      auto out = s->studio().moveObjectsToLayer(s->backend().selectedObjects(), id);
                      s->report(out);
                      s->save();
                      popup->refresh();
                  }}},
                0.4f);
}
